const m = (n: number) => String(n).replace(".", ",");
const desloc = (n: number): Trait => ({ name: "Deslocamento", description: `Seu deslocamento base de caminhada é ${m(n)} metros.` });
const visao = (n = 18): Trait => ({
  name: "Visão no Escuro",
  description: `Você enxerga na penumbra a até ${n} metros como se fosse luz plena, e no escuro como se fosse na penumbra. Você não pode discernir cores no escuro, apenas tons de cinza.`,
});
const idiomas = (...l: string[]): Trait => ({ name: "Idiomas", description: `Você pode falar, ler e escrever ${l.join(", ").replace(/, ([^,]*)$/, " e $1")}.` });
const t = (name: string, description: string): Trait => ({ name, description });
const FLEX = t("Aumento nos Valores de Habilidade", "Você aumenta um valor de habilidade em 2 e outro em 1, ou três valores diferentes em 1 cada, à sua escolha.");

interface R {
  id: string; name: string; summary: string;
  ab?: Partial<Record<AbilityKey, number>>;
  choice?: Race["abilityChoice"];
  age: string; alignment: string; size?: Size; sizeNote: string;
  speed: number; languages: string[]; extra?: number;
  traits: Trait[]; prof?: Race["proficiencies"]; sub?: Subrace[];
}

const race = (r: R): Race => ({
  id: r.id, name: r.name, summary: r.summary,
  abilityBonuses: r.ab ?? {},
  ...(r.choice ? { abilityChoice: r.choice } : {}),
  age: r.age, alignment: r.alignment, size: r.size ?? "Médio", sizeNote: r.sizeNote,
  speed: r.speed, languages: r.languages,
  ...(r.extra ? { extraLanguages: r.extra } : {}),
  traits: r.traits,
  ...(r.prof ? { proficiencies: r.prof } : {}),
  subraces: r.sub ?? [],
});

const sub = (id: string, name: string, ab: Subrace["abilityBonuses"], traits: Trait[], extra?: Partial<Subrace>): Subrace => ({ id, name, abilityBonuses: ab, traits, ...extra });

